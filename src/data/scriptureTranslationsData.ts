/**
 * Resolves translation with fallback hierarchy:
 * 1. Runtime component cache (e.g. AI-translated dynamic verses)
 * 2. Precompiled canonical translations in requested language
 * 3. Verse's own embedded translations dictionary
 * 4. Original verse translation (English)
 */
export function resolveVerseTranslation(
  verse: VerseCorpusItem,
  targetLang: ExplanationLanguage,
  runtimeCache?: Record<string, Partial<Record<ExplanationLanguage, VerseTranslationData>>>
): { translation: string; deepInsight: string; isPrecompiled: boolean } {
  // 1. Runtime cache
  if (runtimeCache?.[verse.id]?.[targetLang]) {
    const cached = runtimeCache[verse.id]![targetLang]!;
    return {
      translation: cached.translation,
      deepInsight: cached.deepInsight || verse.deepInsight,
      isPrecompiled: true
    };
  }

  // 2. Precompiled canonical database
  const canonicalEntry = CANONICAL_VERSE_TRANSLATIONS[verse.id]?.[targetLang];
  if (canonicalEntry) {
    return {
      translation: canonicalEntry.translation,
      deepInsight: canonicalEntry.deepInsight || verse.deepInsight,
      isPrecompiled: true
    };
  }

  // 3. Verse's own translations dictionary if present
  const verseTranslations = (verse as any).translations as Partial<Record<string, string>> | undefined;
  const verseInsights = (verse as any).deepInsights as Partial<Record<string, string>> | undefined;
  if (verseTranslations && verseTranslations[targetLang]) {
    return {
      translation: verseTranslations[targetLang]!,
      deepInsight: (verseInsights && verseInsights[targetLang]) || verse.deepInsight,
      isPrecompiled: true
    };
  }

  // 4. Default fallback (Original text in English)
  return {
    translation: verse.translation,
    deepInsight: verse.deepInsight,
    isPrecompiled: targetLang === "English"
  };
}
